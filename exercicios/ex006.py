# Crie um algoritmo que leia um número e mostre o seu dobro, triplo e raíz quadrada.
numero = int(input("Número: "))
print("O dobro deste número é \33[1;33m{}\33[m;".format(numero*2))
print("O triplo deste número é \33[1;33m{}\33[m;".format(numero*3))
print("A raíz quadrada deste número é \33[1;33m{}\33[m.".format(numero**(1/2)))